#!/usr/bin/env python3
"""
Turns a raw modifier block from the game files into the text the game shows,
e.g. {founder_species_growth_mult: 0.2, refugee_attraction: -0.3} ->
"Founder Species Pop Growth: +20%; Refugee Attraction: -30%".

Shared by every extractor (traits, civics/origins, ethics, ascension perks,
traditions, ruler traits), which used to each print the raw keys.

Labels come from the game localization (`mod_<key>`, any case). The game
generates the label of a few modifiers in code (no localization entry): job
efficiency ones are rebuilt from the job names, the rest is humanized.

The display format (percentage or plain number) is decided by the engine and
not exposed in the game files, so it follows the game's naming convention:
`_mult` / `_perc` -> percentage, `_add` -> plain number, any other key ->
percentage for a fractional value (0.1 happiness = +10%), plain number for a
whole one (+1 starting skill). Checked by hand on every key used in 4.6.
"""

import re
from typing import Any, Dict, Optional

from localization_parser import _LAST_LOCALIZATIONS, get_localized_text, clean_localized_text

_lower_index: Dict[str, str] = {}
_lower_index_size = -1

SMALL_WORDS = {'and', 'or', 'of', 'for', 'per', 'to', 'in', 'on', 'the', 'a'}


def _localization_lookup(key: str) -> Optional[str]:
    """Case-insensitive localization lookup (the game mixes mod_x and MOD_X)."""
    global _lower_index, _lower_index_size
    if _lower_index_size != len(_LAST_LOCALIZATIONS):
        _lower_index = {k.lower(): k for k in _LAST_LOCALIZATIONS}
        _lower_index_size = len(_LAST_LOCALIZATIONS)
    real_key = _lower_index.get(key.lower())
    return _LAST_LOCALIZATIONS.get(real_key) if real_key else None


def _humanize(text: str) -> str:
    words = [w for w in text.split('_') if w]
    return ' '.join(w if (i > 0 and w in SMALL_WORDS) else w.capitalize() for i, w in enumerate(words))


def _job_name(job: str, plural: bool) -> Optional[str]:
    for key in (f'job_{job}', f'pop_cat_{job}', job):
        text = _localization_lookup(key + ('_plural' if plural else ''))
        if text:
            return text
    return None


def _engine_function(match) -> str:
    """Engine-side localization functions used by modifier labels, e.g.
    [GetBureaucratSwapPluralWithIcon] -> Bureaucrats, [GetSpecialistPlural] ->
    Specialists, [GetCrimeDeviancy] -> Crime. Unknown ones are kept, so the
    caller falls back to a label built from the modifier key."""
    name = match.group(1)
    if name == 'CrimeDeviancy':
        return 'Crime'
    if name == 'CitizenOrCrew':
        return 'Citizen'
    job = re.match(r'^([A-Z][a-z]+)(?:Swap)?(Plural)?(?:WithIcon)?$', name)
    if job:
        found = _job_name(job.group(1).lower(), bool(job.group(2)))
        if found:
            return found
    return match.group(0)


def _icon_word(match) -> str:
    """£unity£ carries the resource name in game: keep it as a word, unless
    the label already spells it right after (£engineering£ Engineering)."""
    name, following = match.group(1), match.group(2)
    word = _humanize(name)
    if following.lower().startswith(word.lower()):
        return following
    return f'{word} {following}'


def _clean_label(raw: str) -> str:
    text = get_localized_text(raw, _LAST_LOCALIZATIONS) if '$' in raw else raw
    for _ in range(3):  # nested $vars$ (a resolved value can hold others)
        if '$' not in text:
            break
        text = re.sub(r'\$([A-Za-z0-9_]+)\$', lambda m: _localization_lookup(m.group(1)) or m.group(0), text)
    text = re.sub(r'\[Get([A-Za-z]+)\]', _engine_function, text)
    text = re.sub(r'§[A-Za-z0-9!]', '', text)
    text = re.sub(r'£([a-z_]+)£\s*(\S*)', _icon_word, text)
    text = clean_localized_text(text, _LAST_LOCALIZATIONS)
    # Leftover engine placeholders ($commander_with_icon$, ...)
    text = re.sub(r'\$([a-z_]+?)(?:_with_icon)?\$', lambda m: _humanize(m.group(1)), text)
    text = text.replace('( ', '(').replace(' )', ')')
    return re.sub(r'\s+', ' ', text).strip(' :')


def modifier_label(key: str) -> str:
    raw = _localization_lookup(f'mod_{key}')
    if raw:
        label = _clean_label(raw)
        if label and not re.search(r'[$\[\]]|individuals', label):
            return label

    # Job efficiency, generated by the engine per job: <job>_jobs_bonus_workforce_mult
    match = re.match(r'^([a-z_]+?)_jobs_bonus_workforce_mult$', key)
    if match:
        job = match.group(1)
        plural = _localization_lookup(f'job_{job}_plural')
        name = _clean_label(plural) if plural else _humanize(job) + 's'
        return f'Job Efficiency for {name}'

    # Per pop category: worker_and_simple_drone_cat_bonus_workforce_mult
    match = re.match(r'^([a-z_]+?)_cat_bonus_workforce_mult$', key)
    if match:
        return f'Job Efficiency for {_humanize(match.group(1))} Jobs'

    return _humanize(re.sub(r'_(add|mult)$', '', key))


# Families always shown as a percentage, whatever the value (-1 experience
# gain is -100%, 1.0 army health is +100%)
PERCENTAGE_SUFFIXES = ('_gain', '_speed', '_happiness', '_attraction', '_habitability', '_damage',
                       '_health', '_chance', '_rate')


def is_percentage(key: str, value: float) -> bool:
    if key.endswith('_mult') or key.endswith('_perc'):
        return True
    if key.endswith('_add'):
        return False
    if key.endswith(PERCENTAGE_SUFFIXES):
        return True
    return not float(value).is_integer()


def format_modifier_value(key: str, value: float) -> str:
    if is_percentage(key, value):
        text = f'{value * 100:.2f}'.rstrip('0').rstrip('.') + '%'
    else:
        text = f'{value:.2f}'.rstrip('0').rstrip('.')
    return ('+' + text) if value > 0 else text


def format_modifier_effects(modifier_data: Any) -> str:
    """Readable text for a modifier block; nested blocks are flattened."""
    if not isinstance(modifier_data, dict):
        return ''
    effects = []
    for key, value in modifier_data.items():
        if isinstance(value, bool):
            continue
        if isinstance(value, (int, float)):
            effects.append(f'{modifier_label(key)}: {format_modifier_value(key, value)}')
        elif isinstance(value, dict):
            nested = format_modifier_effects(value)
            if nested:
                effects.append(nested)
    return '; '.join(effects)
